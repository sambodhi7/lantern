import test from 'node:test';
import assert from 'node:assert/strict';
import { createServer } from 'node:http';
import { network } from 'hardhat';
import { TestnetService } from './testnet.mjs';
import { TrustStore } from './trust.mjs';

test('wallet deployment, campaign creation and donation are independently checked against actual contract execution', {timeout:90000},async()=>{
  const connection=await network.create();
  const {provider,viem}=connection;
  const [owner,donor]=await viem.getWalletClients();
  const client=await viem.getPublicClient();
  const rpc=createServer(async(req,res)=>{
    try{
      const chunks=[];for await(const chunk of req)chunks.push(chunk);
      const call=JSON.parse(Buffer.concat(chunks));
      const result=await provider.request({method:call.method,params:call.params});
      res.writeHead(200,{'content-type':'application/json'});res.end(JSON.stringify({jsonrpc:'2.0',id:call.id,result}));
    }catch{res.writeHead(500);res.end('{}');}
  });
  await new Promise(resolve=>rpc.listen(0,'127.0.0.1',resolve));
  try{
    const service=new TestnetService({rpcUrl:`http://127.0.0.1:${rpc.address().port}`,chainId:await client.getChainId()});
    const trust=new TrustStore(null);
    const deploy=await service.prepare(trust,{action:'deploy',wallet:owner.account.address});
    const deployedTx=await owner.sendTransaction({account:owner.account,data:deploy.transaction.data});
    await client.waitForTransactionReceipt({hash:deployedTx,timeout:20000,pollingInterval:100});
    const deployed=await service.confirm(trust,{action:'deploy',wallet:owner.account.address,txHash:deployedTx});
    assert.match(deployed.contract,/^0x[0-9a-f]{40}$/);
    assert.equal(deployed.owner,owner.account.address.toLowerCase());
    await assert.rejects(service.prepare(trust,{action:'create',wallet:donor.account.address}),/deploy/);
    const create=await service.prepare(trust,{action:'create',wallet:owner.account.address});
    const campaignTx=await owner.sendTransaction({account:owner.account,to:create.transaction.to,data:create.transaction.data});
    await client.waitForTransactionReceipt({hash:campaignTx,timeout:20000,pollingInterval:100});
    const campaign=await service.confirm(trust,{action:'create',wallet:owner.account.address,txHash:campaignTx});
    assert.equal(campaign.campaignId,'1');
    const prepared=await service.prepare(trust,{action:'donate',wallet:donor.account.address,amount:'0.001'});
    const donationTx=await donor.sendTransaction({account:donor.account,to:prepared.transaction.to,data:prepared.transaction.data,value:BigInt(prepared.transaction.value)});
    await client.waitForTransactionReceipt({hash:donationTx,timeout:20000,pollingInterval:100});
    await assert.rejects(service.confirm(trust,{action:'donate',wallet:owner.account.address,txHash:donationTx}),/sender/);
    await service.confirm(trust,{action:'donate',wallet:donor.account.address,txHash:donationTx});
    await service.confirm(trust,{action:'donate',wallet:donor.account.address,txHash:donationTx});
    assert.equal(service.config(trust).donations.length,1);
    assert.equal(await client.getBalance({address:deployed.contract}),1000000000000000n);
    assert.equal(trust.get('harbor-hands').campaign.fundraising.raisedInr,1000000,'test tokens do not inflate INR raised');
    await assert.rejects(service.voterChallenge(trust,{wallet:owner.account.address}),/has not donated/);
    const challenge=await service.voterChallenge(trust,{wallet:donor.account.address});
    const wrongSignature=await owner.signMessage({account:owner.account,message:challenge.message});
    await assert.rejects(service.voterSession(trust,{id:challenge.id,signature:wrongSignature}),/does not match/);
    const signature=await donor.signMessage({account:donor.account,message:challenge.message});
    const session=await service.voterSession(trust,{id:challenge.id,signature});
    assert.equal(session.source,'verified_testnet_donor');
    const reviewed=trust.vote('harbor-hands','water-pump-071',session.token,true);
    assert.equal(reviewed.score,72);
    await assert.rejects(service.voterSession(trust,{id:challenge.id,signature}),/expired/);
    const next=trust.createCampaign('harbor-hands',{name:'New school learning supplies',story:'Purchase learning tables and materials for students at the community school.',category:'Education',targetInr:100000});
    const localCampaignId=next.campaign.id;
    assert.equal(service.config(trust,localCampaignId).campaignId,null);
    await assert.rejects(service.confirm(trust,{action:'create',wallet:owner.account.address,txHash:campaignTx,localCampaignId}),/another campaign/);
    const createNext=await service.prepare(trust,{action:'create',wallet:owner.account.address,localCampaignId});
    const nextTx=await owner.sendTransaction({account:owner.account,to:createNext.transaction.to,data:createNext.transaction.data});
    await client.waitForTransactionReceipt({hash:nextTx,timeout:20000,pollingInterval:100});
    const activated=await service.confirm(trust,{action:'create',wallet:owner.account.address,txHash:nextTx,localCampaignId});
    assert.equal(activated.campaignId,'2');
    await assert.rejects(service.confirm(trust,{action:'donate',wallet:donor.account.address,txHash:donationTx,localCampaignId}),/not a donation/);
    await assert.rejects(service.voterChallenge(trust,{wallet:donor.account.address,localCampaignId}),/has not donated/);
    const nextDonation=await service.prepare(trust,{action:'donate',wallet:donor.account.address,amount:'0.002',localCampaignId});
    const nextDonationTx=await donor.sendTransaction({account:donor.account,to:nextDonation.transaction.to,data:nextDonation.transaction.data,value:BigInt(nextDonation.transaction.value)});
    await client.waitForTransactionReceipt({hash:nextDonationTx,timeout:20000,pollingInterval:100});
    await service.confirm(trust,{action:'donate',wallet:donor.account.address,txHash:nextDonationTx,localCampaignId});
    await service.confirm(trust,{action:'donate',wallet:donor.account.address,txHash:nextDonationTx,localCampaignId});
    assert.equal(trust.get('harbor-hands',undefined,localCampaignId).blockchain.testEthDonated,'0.002');
    assert.equal(trust.get('harbor-hands').blockchain.testEthDonated,'0.001');
    assert.equal(service.config(trust,localCampaignId).donations.length,1);
    const nextChallenge=await service.voterChallenge(trust,{wallet:donor.account.address,localCampaignId});
    const nextSignature=await donor.signMessage({account:donor.account,message:nextChallenge.message});
    const nextSession=await service.voterSession(trust,{id:nextChallenge.id,signature:nextSignature});
    assert.equal(trust.findDonor(nextSession.token).campaignId,localCampaignId);
    assert.throws(()=>trust.vote('harbor-hands','water-pump-071',nextSession.token,true),/Only donors to this campaign/);
    assert.equal(await client.getBalance({address:deployed.contract}),3000000000000000n);
    assert.throws(()=>trust.reset(),/escrow links must be preserved/);
    assert.equal(service.config(trust,localCampaignId).campaignId,'2','reset cannot discard a funded campaign');
    assert.equal(service.config(trust).contract,deployed.contract);
  }finally{await new Promise(resolve=>rpc.close(resolve));await connection.close();}
});
